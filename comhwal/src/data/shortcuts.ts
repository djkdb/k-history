export const SHORTCUT_MAP: Record<string, Shortcut> = Object.fromEntries(
  SHORTCUTS.map((s) => [s.id, s]),
);

export function shortcutsFor(grade: Grade, app?: Shortcut["app"]): Shortcut[] {
  return SHORTCUTS.filter(
    (s) => inGrade(grade, s.minGrade) && (!app || s.app === app),
  );
}

/** 갈래 목록 — 데이터에 나온 순서를 지킨다 */
export function shortcutTopics(grade: Grade): string[] {
  const seen: string[] = [];
  for (const s of shortcutsFor(grade)) {
    if (!seen.includes(s.topic)) seen.push(s.topic);
  }
  return seen;
}
