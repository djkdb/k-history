/**
 * 쉽게 말하면 — 문장마다 앞에 다는 그림 글자를 문장의 말과 말투로 고른다.
 * 글은 새로 쓰지 않는다; 눈이 문장 단위로 걸리게 할 뿐이다.
 *
 *   ⚠️ 오해·헷갈림·주의   📌 예를 들어   🤔 물음   🔑 **용어** = 풀이   💡 즉·결국·그래서
 *   그다음 비유에 나온 물건(📚 도서관 · 🍳 레시피 · 📦 창고 …)   ➡️ 흐름(→)   👉 그 밖
 * ①②③ 으로 시작하는 문장은 번호를 그대로 앞에 세운다.
 */
const RULES: [RegExp, string][] = [
  [/오해|헷갈|주의|실수|착각|함정|조심|틀리기 쉽/, "⚠️"],
  [/^(예를 들어|예컨대|가령|이를테면|예:|예\))/, "📌"],
  [/\?["”’)]?$/, "🤔"],
  [/^\*\*[^*]+\*\*\s*(\([^)]*\)\s*)?(=|:|—|은 |는 )/, "🔑"],
  [/^(즉|결국|그래서|따라서|요컨대|한마디로|핵심|정리하면)/, "💡"],
];

/** 비유에 자주 나오는 물건 — 앞에 있는 것부터 */
const THINGS: [RegExp, string][] = [
  [/도서관|책장|사서|요리책|사전|책을|책은|책이/, "📚"],
  [/레시피|요리|식당|주방|재료|메뉴/, "🍳"],
  [/창고|택배|상자|봉투/, "📦"],
  [/설계도|건물|다리를|집을 짓|짓기|공사/, "🏗️"],
  [/자동차|운전|엔진|자전거/, "🚗"],
  [/은행|계좌|돈|벌금|가격|비용/, "💰"],
  [/학생|학과|학년|수업|공부|시험|문제집|정답|점수|성적/, "🎓"],
  [/직원|회사|부양가족|관리자|상사|부서/, "👔"],
  [/손님|고객|가게|마트|주문/, "🛒"],
  [/사과|과일|배 /, "🍎"],
  [/사진|그림|화면|색깔|색을|색이/, "🖼️"],
  [/지도|여행|길을|길이 |도로/, "🗺️"],
  [/아파트|주소|우편|쪽지|편지/, "✉️"],
  [/게임|보상|칭찬/, "🎮"],
  [/소리|음악|노래|목소리/, "🎵"],
  [/나무|숲|가지|뿌리|잎/, "🌳"],
  [/단어|글자|철자|문장/, "🔤"],
  [/숫자|계산|더하|곱하|정수|자리/, "🔢"],
  [/시간|시계|매일|순서대로|기다/, "⏰"],
  [/목록|명단|출석|번호표|표에|칸에/, "📋"],
  [/찾기|찾는|검색|뒤지/, "🔍"],
  [/팀|함께|여럿이|사람들|명이/, "👥"],
];

export const CIRCLED = /^([①-⑳])\s*/;

export function easyIcon(s: string): string {
  const t = s.trim();
  for (const [re, ic] of RULES) if (re.test(t)) return ic;
  for (const [re, ic] of THINGS) if (re.test(t)) return ic;
  if (t.includes("→")) return "➡️";
  return "👉";
}
