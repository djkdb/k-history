/** 굵은 글씨 내용에서 사전 키를 만든다: 앞 번호 "1) " 를 떼고 소문자로 */
export function glossOf(text: string): string | undefined {
  if (/[가-힣]/.test(text)) return undefined;
  const k = text.replace(/^\s*\d+\)\s*/, "").trim().toLowerCase();
  return GLOSS[k];
}
